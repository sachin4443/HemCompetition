using System.Security.Cryptography;
using Microsoft.Extensions.Options;

namespace HemCompetition.API.Infrastructure;

/// <summary>
/// Stores evidence and question images. PostgreSQL holds only the key and metadata.
/// Swap this implementation for an S3/Azure Blob one without touching callers.
/// </summary>
public interface IFileStorage
{
    /// <returns>SHA-256 of the stored bytes (lower-case hex).</returns>
    Task<string> SaveAsync(string key, Stream content, CancellationToken ct = default);
    Task<Stream?> OpenAsync(string key);
    Task DeleteAsync(string key);
}

public sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(IOptions<StorageOptions> options, IWebHostEnvironment env)
    {
        _root = Path.GetFullPath(Path.IsPathRooted(options.Value.Root)
            ? options.Value.Root
            : Path.Combine(env.ContentRootPath, options.Value.Root));
        var webRoot = env.WebRootPath == null ? null : Path.GetFullPath(env.WebRootPath) + Path.DirectorySeparatorChar;
        if (webRoot != null && (_root + Path.DirectorySeparatorChar).StartsWith(webRoot, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Storage:Root must not be inside wwwroot - stored files would be publicly downloadable.");
        Directory.CreateDirectory(_root);
    }

    private string Resolve(string key)
    {
        // Keys are generated by the server, but resolve defensively so a key can never leave the root.
        var full = Path.GetFullPath(Path.Combine(_root, key));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Invalid storage key.");
        return full;
    }

    public async Task<string> SaveAsync(string key, Stream content, CancellationToken ct = default)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        using var sha = SHA256.Create();
        await using (var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true))
        await using (var hashing = new CryptoStream(file, sha, CryptoStreamMode.Write))
            await content.CopyToAsync(hashing, ct);
        return Convert.ToHexStringLower(sha.Hash!);
    }

    public Task<Stream?> OpenAsync(string key)
    {
        var path = Resolve(key);
        return Task.FromResult<Stream?>(File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true)
            : null);
    }

    public Task DeleteAsync(string key)
    {
        var path = Resolve(key);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }
}

/// <summary>Decides what an uploaded file really is from its first bytes, not from what the client claims.</summary>
public static class FileSniffer
{
    public static string? DetectContentType(ReadOnlySpan<byte> head)
    {
        if (head.Length >= 3 && head[0] == 0xFF && head[1] == 0xD8 && head[2] == 0xFF) return "image/jpeg";
        if (head.Length >= 8 && head[..8].SequenceEqual(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A })) return "image/png";
        if (head.Length >= 12 && head[..4].SequenceEqual("RIFF"u8) && head[8..12].SequenceEqual("WEBP"u8)) return "image/webp";
        if (head.Length >= 4 && head[0] == 0x1A && head[1] == 0x45 && head[2] == 0xDF && head[3] == 0xA3) return "video/webm";
        if (head.Length >= 12 && head[4..8].SequenceEqual("ftyp"u8)) return "video/mp4";
        return null;
    }

    public static string Extension(string contentType) => contentType switch
    {
        "image/jpeg" => ".jpg", "image/png" => ".png", "image/webp" => ".webp",
        "video/webm" => ".webm", "video/mp4" => ".mp4", _ => ".bin"
    };

    /// <summary>Reads the upload into memory (bounded by <paramref name="maxBytes"/>) and identifies it.</summary>
    public static async Task<(MemoryStream Content, string ContentType)> ReadVerifiedAsync(
        IFormFile file, long maxBytes, IReadOnlyCollection<string> allowed)
    {
        if (file.Length == 0) throw ApiException.BadRequest("The file is empty.");
        if (file.Length > maxBytes) throw new ApiException(413, $"The file is larger than the {maxBytes / 1024} KB limit.", "FILE_TOO_LARGE");
        var buffer = new MemoryStream((int)file.Length);
        await file.CopyToAsync(buffer);
        var type = DetectContentType(buffer.GetBuffer().AsSpan(0, (int)Math.Min(16, buffer.Length)));
        if (type == null || !allowed.Contains(type)) throw new ApiException(415, "This file type is not allowed.", "FILE_TYPE");
        buffer.Position = 0;
        return (buffer, type);
    }
}
